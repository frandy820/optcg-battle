// 名字展开：base 本体 + 变体（「{名}·{变体}」），去重、洗牌（seed 固定可复现）后取 count 个
export function expandNames(faction, count, rng) {
  const { base, variants } = NAME_POOL[faction];
  const out = [];
  for (const n of base) out.push(n);
  // 变体扩展：按变体轮次逐层补（本体全员先入，再撒第一变体层，再第二层……）
  if (out.length < count) {
    for (let vi = 0; vi < variants.length && out.length < count; vi++) {
      for (let bi = 0; bi < base.length && out.length < count; bi++) {
        out.push(`${base[bi]}·${variants[vi]}`);
      }
    }
  }
  // 洗牌（ Fisher-Yates，外部注入 rng 保持确定性）
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out.slice(0, count);
}
